const DICTS: Record<Locale, Record<Key, string>> = { zh, en };

export const isLocale = (v: unknown): v is Locale => LOCALES.includes(v as Locale);

/** Look up `key` in `locale` (default zh), filling `{name}` placeholders from `params`. Unknown placeholders are left as-is. */
export function t(key: Key, locale: Locale = "zh", params?: Record<string, string | number>): string {
  const s = (DICTS[locale] ?? DICTS.zh)[key] ?? DICTS.zh[key] ?? key;
  return params ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m)) : s;
}

/** Parse a raw Cookie header / document.cookie string; anything unrecognised falls back to zh. */
export function localeFromCookie(raw: string | undefined): Locale {
  const v = raw
    ?.split(/;\s*/)
    .find((p) => p.startsWith(`${LOCALE_COOKIE}=`))
    ?.slice(LOCALE_COOKIE.length + 1);
  return isLocale(v) ? v : "zh";
}
